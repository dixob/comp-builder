#!/usr/bin/env python3
"""Build a static, isolated worker scorer from the website's scoring source.

No runtime eval or downloaded code. Deployment checks the generated module so
formula changes cannot silently leave the background scorer on an older model.
"""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'worker/src/scoring.generated.mjs'


def build():
    html = (ROOT / 'index.html').read_text()
    source = html[html.index('const ROLES ='):html.index('// --- collection status')]
    # Remove browser networking and rendering; retain the exact scoring bodies.
    start, end = source.index('// Prefetch matchup tables'), source.index('function matchupRec(')
    source = source[:start] + source[end:]
    start, end = source.index('function evidenceHTML('), source.index('// Original pre-review model')
    source = source[:start] + source[end:]
    digest = hashlib.sha256(source.encode()).hexdigest()
    return f'''// Generated by scripts/build_worker_scoring.py. Do not edit.
// Scoring source SHA-256: {digest}
export const SCORING_SOURCE_SHA = "{digest}";
export function createScorer(players, meta, draft, options = {{}}) {{
// The website's preference reads use default values here; no browser is needed.
const localStorage = {{getItem: key => key === "strictRole" && options.strictRole ? "1" : null, removeItem() {{}}}};
const uniqueExclude = new Set();
const flexOnly = options.flexOnly === true;
{source}
D=players; META=meta; draftMode=true;
liveBans=new Set(draft.bans||[]); liveEnemy=new Set(draft.enemy||[]); liveOurs=draft.ours||[];
masteryIdx=Object.fromEntries(D.players.map(p=>[p.riotId,Object.fromEntries(p.mastery.map(m=>[m.championId,m.points]))]));
champPairIdx=Object.fromEntries(D.championPairs.map(p=>[p.pa+'|'+p.a+':'+p.pb+'|'+p.b,p]));
playerPairIdx=Object.fromEntries(D.playerPairs.map(p=>[[p.a,p.b].sort().join('|'),p]));
const assign=ROLES.map(role=>{{const p=liveOurs.find(p=>p.position===role);
  const player=D.players.find(a=>a.riotId.toLowerCase()===String(p?.riotId||'').toLowerCase());
  return {{role,player:player?.riotId,champ:p?.championId}};
}});
if (!completeComposition(assign)) throw new Error('Five tracked players and distinct picks/roles are required');
const requests=new Map();
for(const cid of liveEnemy) for(const role of Object.keys(laneDist(cid,true)))
  requests.set(cid+'|'+OPGG_POS[role],{{champ:cid,pos:OPGG_POS[role]}});
for(const pick of assign) requests.set(pick.champ+'|'+OPGG_POS[pick.role],{{champ:pick.champ,pos:OPGG_POS[pick.role]}});
return {{modelVersion:MODEL_VERSION,requests:[...requests.values()],
  record(tables, capturedAt) {{
    counterIdx=tables; dAdjCache={{}}; candCache={{}};
    const record=predictionRecord(assign,capturedAt);
    record.settings.capturePolicy='server-standard-v1';
    record.settings.flexOnly=flexOnly;
    record.settings.matchupTablesLoaded=Object.keys(tables);
    return record;
  }}
}};
}}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = build()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != expected:
            raise SystemExit('Worker scoring is stale. Run python3 scripts/build_worker_scoring.py')
        print('Worker scoring matches the website source.')
    else:
        TARGET.write_text(expected)
        print(f'Generated {TARGET.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
